/**
 * 本文の作り方（プロンプト v3・「情報の型」で分解してから書かせる）。
 *
 * 背景（2026-07-24 実測）: 字数レンジのある項目が**全件下限割れ**（17箇所中17箇所が短い側）。
 * 「字数を守れ」と明示するだけでは直らなかった（再計測で 21〜27字 / 規定 40〜70字）。
 *
 * 原因の見立て: LLM は「説明文を書け」と言われると最も一般的な一文へ圧縮する。
 * 長さは結果であって指示で伸びない。**書く前に材料を出させれば、文は自然に伸びる。**
 *
 * マスター案（連想語を5つ鎖状に出して使う）との違い:
 * 材料を「近い語」ではなく **情報の型（誰に / 何を / 何が違う）** にした。
 * 連想語は鎖が伸びるほど業種文脈から離れ（料金→相場→市場→経済）、語を埋めるための
 * 詰め込み文と事実の創作を誘発する。型なら材料は依頼文の中から取るしかないので逸れない。
 *
 * 実装上の要点: 材料は同じ JSON の **sections より前** に置かせる。LLM は前から順に
 * 生成するため、先に書いた材料が後続の本文を条件付ける（1回の呼び出しで思考させる）。
 * 材料は組み立てでは使わない（assemblePage は読まない）＝描画には影響しない。
 */

